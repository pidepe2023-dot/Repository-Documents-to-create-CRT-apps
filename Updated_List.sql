SELECT DISTINCT
A.BRAND AS BRAND,
A.NWKREF AS NAID,
A.LOCATIONID,
A.PRIAGNTID,
A.RGN AS REGION,
A.CONTRY AS COUNTRY_CODE,
P.CTYNAME AS COUNTRY_NAME,
A.CTGRY,
A.CUSTLSTIND AS CLI,
R.AGNTID,
A.AGTNME AS AGENT_NAME,
A.AGTSTS AS AGENT_STATUS,
A.PASTATUS AS Primary_agent_Id_status,
A.ASTRDT AS AGENT_START_DATE,
A.AADDR1,
A.AADDR2,
A.ACITY AS CITY,
A.ASTATE AS STATE,
A.ASTPRV AS PROVINCE,
A.ZIPCDE AS ZIP_CODE,
A.CLSDES AS CLASS_DESCRIPTION,
CASE 
    WHEN A.SWBFLG = 'N' 
        THEN 'NON-SWB' 
        ELSE 'SWB' 
    END AS SWB_Non_SWB, 
A.VOLUME_INDICATOR,
A.AHOMON AS OPEN_MON,
A.AHCMON AS CLOSE_MON,
A.AHOSAT AS OPEN_SAT,
A.AHCSAT AS CLOSE_SAT,
A.AHOSUN AS OPEN_SUN,
A.AHCSUN AS CLOSE_SUN,
A.AGLSTMTPAY as Last_Money_Transfer_Pay,
A.AGLSTMTSND as Last_Money_Transfer_Send,
A.TERMINATION_CODE,
CASE
    WHEN A.TERMINATION_CODE IS NOT NULL 
         AND TRIM(A.TERMINATION_CODE) <> '' 
    THEN 'Terminada'
    ELSE 'Activa'
END AS STATUS,
T.TERMLSTMTTXN


FROM ADH.AGENT_MASTER_PII.VW_AGENT_MT  A
LEFT JOIN ADH.AGENT_MASTER_PII.VW_TERMINAL R ON R.AGNTID=A.PRIAGNTID
LEFT JOIN ADH.AGENT_MASTER_PII.VW_COUNTRY P ON P.CTYCODE=A.CONTRY
LEFT JOIN ADH.AGENT_MASTER_PII.VW_TERMINAL_MT T ON T.AGNTID=A.PRIAGNTID

WHERE 
A.RGN IN ('LACA')
AND A.LOCATIONID IS NOT NULL
--and P.CTYNAME in ()
--AND A.NWKREF IN ()
--AND A.AGTSTS IN ('A')
--AND A.PASTATUS IN ('')
--AND A.AGLSTMTPAY > ('2026-01-01')
--AND A.AGLSTMTSND > ('2026-01-01')
AND A.LOCATIONID IN ()

ORDER BY A.LOCATIONID, A.CONTRY

